// Regenerates src/render/gameIconPaths.ts from the game-icons.net glyphs named in src/render/icons.ts.
// Icons by Lorc, Delapouite and Lucas (lucasms) from https://game-icons.net, CC BY 3.0.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/render/icons.ts', import.meta.url), 'utf8');
const names = [...new Set([...src.matchAll(/'([a-z0-9-]+\/[a-z0-9-]+)'/g)].map((m) => m[1]))].sort();
const out = {};
for (const name of names) {
  const res = await fetch(`https://raw.githubusercontent.com/game-icons/icons/master/${name}.svg`);
  if (!res.ok) throw new Error(`${name}: ${res.status}`);
  const svg = await res.text();
  // Every glyph is a black 512 square followed by white paths; keep the white ones.
  const paths = [...svg.matchAll(/<path([^>]*)\/>/g)].filter((m) => !/d="M0 0h512v512H0z"/.test(m[1])).map((m) => /d="([^"]+)"/.exec(m[1])[1]);
  out[name] = paths.join(' ');
}
const body = Object.entries(out).map(([k, v]) => `  '${k}': '${v}',`).join('\n');
writeFileSync(new URL('../src/render/gameIconPaths.ts', import.meta.url),
  `// Generated by scripts/build-icons.mjs. Glyphs from https://game-icons.net (CC BY 3.0).\nexport const GAME_ICON_PATHS: Record<string, string> = {\n${body}\n};\n`);
console.log(`${names.length} icons`);
